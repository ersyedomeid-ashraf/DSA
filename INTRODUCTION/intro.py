# Introduction to DSA


# Example of storing data using a list
numbers = [10, 20, 30, 40, 50]

print("Numbers:", numbers)


# Accessing data
print("First number:", numbers[0])
print("Last number:", numbers[-1])


# Finding the sum
total = sum(numbers)

print("Sum:", total)


# Finding the largest number
largest = max(numbers)

print("Largest number:", largest)
